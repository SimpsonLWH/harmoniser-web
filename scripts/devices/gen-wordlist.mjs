// Turns scripts/devices/eff_short_wordlist_1.txt (as published by the EFF) into src/core/wordlist.ts.
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("./eff_short_wordlist_1.txt", import.meta.url);
const target = new URL("../../lib/devices/wordlist.ts", import.meta.url);
const words = readFileSync(source, "utf8")
  .split("\n")
  .filter((line) => line.trim() !== "")
  .map((line) => line.split("\t")[1].trim());
if (words.length !== 1296) {
  throw new Error(`expected 1296 words, got ${words.length}`);
}
const rows = [];
for (let i = 0; i < words.length; i += 12) {
  rows.push("  " + words.slice(i, i + 12).map((word) => JSON.stringify(word)).join(", ") + ",");
}
writeFileSync(
  target,
  `// Generated by scripts/devices/gen-wordlist.mjs. Do not edit.
//
// EFF Short Wordlist #1 ("eff_short_wordlist_1.txt", 1,296 words), by the Electronic Frontier
// Foundation: https://www.eff.org/dice. Licensed under CC BY 3.0 US
// (https://creativecommons.org/licenses/by/3.0/us/). See NOTICE.
export const EFF_SHORT_WORDLIST: readonly string[] = [
${rows.join("\n")}
];
`,
);
